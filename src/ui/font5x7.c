/* The glyph for a codepoint that needs no composition: ASCII, an alias for one, or a literal
   cell. Returns false when there is none, leaving `columns` untouched. */
static bool font_base_glyph(uint32_t codepoint, uint8_t columns[MESH_FONT_WIDTH]) {
    if (codepoint >= 0x20U && codepoint <= 0x7EU) {
        memcpy(columns, k_ascii[codepoint - 0x20U], MESH_FONT_WIDTH);
        return true;
    }

    for (size_t i = 0; i < sizeof k_aliases / sizeof k_aliases[0]; ++i) {
        if (k_aliases[i].codepoint == codepoint) {
            memcpy(columns, k_ascii[(unsigned char)k_aliases[i].ascii - 0x20U], MESH_FONT_WIDTH);
            return true;
        }
    }

    for (size_t i = 0; i < sizeof k_literals / sizeof k_literals[0]; ++i) {
        if (k_literals[i].codepoint == codepoint) {
            memcpy(columns, k_literals[i].columns, MESH_FONT_WIDTH);
            return true;
        }
    }

    return false;
}

static const struct font_composed *font_find_composed(uint32_t codepoint) {
    for (size_t i = 0; i < sizeof k_composed / sizeof k_composed[0]; ++i) {
        if (k_composed[i].codepoint == codepoint) {
            return &k_composed[i];
        }
    }
    return NULL;
}

/* True when any column of the glyph occupies row 0 or row 1, the rows a mark wants. */
static bool font_rows_taken(const uint8_t columns[MESH_FONT_WIDTH]) {
    for (int col = 0; col < MESH_FONT_WIDTH; ++col) {
        if ((columns[col] & 0x03U) != 0U) {
            return true;
        }
    }
    return false;
}

bool mesh_font5x7_glyph(uint32_t codepoint, struct mesh_font_glyph *out) {
    if (out == NULL) {
        return false;
    }
    memset(out, 0, sizeof *out);

    if (font_base_glyph(codepoint, out->columns)) {
        return true;
    }

    const struct font_composed *composed = font_find_composed(codepoint);
    if (composed == NULL || !font_base_glyph(composed->base, out->columns)) {
        memcpy(out->columns, k_tofu, MESH_FONT_WIDTH);
        memset(out->above, 0, sizeof out->above);
        return false;
    }

    if (composed->mark == MARK_NONE) {
        return true;
    }

    const uint8_t *mark = k_marks[composed->mark];
    if (!font_rows_taken(out->columns)) {
        for (int col = 0; col < MESH_FONT_WIDTH; ++col) {
            out->columns[col] |= mark[col];
        }
        return true;
    }

    /* No room in the cell: collapse the mark to its silhouette and hang it in the line gap. */
    for (int col = 0; col < MESH_FONT_WIDTH; ++col) {
        out->above[col] = mark[col] != 0U ? 0x01U : 0x00U;
    }
    return true;
}

bool mesh_font5x7_has_glyph(uint32_t codepoint) {
    uint8_t columns[MESH_FONT_WIDTH];
    if (font_base_glyph(codepoint, columns)) {
        return true;
    }
    const struct font_composed *composed = font_find_composed(codepoint);
    return composed != NULL && font_base_glyph(composed->base, columns);
}
