/*
 * Diacritics, drawn in rows 0 and 1 of the cell - the two rows this font's lowercase leaves
 * clear. Bit 0 is row 0, bit 1 is row 1, so a mark that wants to sit tight against its letter
 * uses bit 1.
 *
 * Where the base letter reaches into those rows (every capital, and the lowercase ascenders)
 * the mark is collapsed to its horizontal silhouette and drawn in the single row above the
 * cell instead. Circumflex, caron, macron and ring all collapse to the same three-pixel bar;
 * at five pixels wide there is no honest way to keep them apart, and the diaeresis, the one
 * mark a reader is likely to be looking for, survives the collapse because its gap is
 * horizontal.
 */
