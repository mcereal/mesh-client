/*
 * The old spelling of everything that moved to inkcell.
 *
 * The UI toolkit this client was built out of is its own library now (third_party/inkcell), and
 * its symbols are named for it: `inkcell_theme_by_id`, `INKCELL_TONE_PRIMARY`,
 * `inkcell_fb_card_begin`. This tree still says `mesh_ui_theme_by_id`, in something over a
 * thousand places across the nav, the settings model, the screen renderers and the tests.
 *
 * Rewriting all of those in the commit that moved the files would have buried the interesting
 * part - four inverted seams and a catalog split - in a diff nobody could read, in a client that
 * is shipped and running on other people\'s devices. So the names are bridged here instead and
 * retired a layer at a time.
 *
 * **This file is temporary and nothing new should use a name in it.** Code written from now on
 * spells the inkcell name; when a layer stops using the old ones, its lines come out of this
 * list. Generated once, mechanically, from the headers as they were before the move - which is
 * why the pairs are exhaustive and in one alphabetical block rather than grouped by meaning.
 *
 * Function-like macros are absent on purpose: every entry is a plain identifier rename, so the
 * preprocessor matches whole tokens and `mesh_ui_theme` does not rewrite `mesh_ui_theme_by_id`.
 * Each of those has a line of its own below.
 */

